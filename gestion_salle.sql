CREATE TABLE SALLE (
    ID_SALLE NUMBER PRIMARY KEY,
    NOM_SALLE VARCHAR2(100) NOT NULL,
    CAPACITE NUMBER NOT NULL,
    TYPE_SALLE VARCHAR2(50),
    DISPONIBILITE VARCHAR2(20) DEFAULT 'Disponible' NOT NULL,
    CONSTRAINT CK_SALLE_CAPACITE CHECK (CAPACITE > 0),
    CONSTRAINT CK_SALLE_DISP CHECK (
        DISPONIBILITE IN ('Disponible', 'Indisponible')
    )
);